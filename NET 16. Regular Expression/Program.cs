#region Regular Expressions (Регулярные выражения)
/*
.           - любой символ (кроме символа новой строки, если не включён режим Singleline)

\w          - любая буква, цифра или символ подчеркивания (_)
\W          - любой символ, кроме буквы, цифры или символа подчеркивания

\s          - любой пробельный символ (пробел, табуляция, перевод строки и т.д.)
\S          - любой непробельный символ

\d          - любая десятичная цифра (0-9)
\D          - любой символ, кроме десятичной цифры

[abc]       - любой один символ из перечисленных
[^abc]      - любой символ, кроме перечисленных

[a-z]       - любой символ из указанного диапазона
[^a-z]      - любой символ, кроме символов указанного диапазона

|           - логическое ИЛИ (альтернатива)

()          - группировка выражений и создание группы захвата
(?:...)     - группировка без сохранения результата (без группы захвата)

*           - шаблон повторяется 0 или более раз
+           - шаблон повторяется 1 или более раз
?           - шаблон повторяется 0 или 1 раз (необязательный элемент)

{n}         - шаблон повторяется ровно n раз
{n,}        - шаблон повторяется не менее n раз
{n,m}       - шаблон повторяется от n до m раз

^           - начало строки
$           - конец строки

\b          - граница слова
\B          - не граница слова

(?=...)     - Положительная проверка вперёд (Positive Lookahead).
              Проверяет, что справа находится указанный шаблон,
              но сам шаблон в результат не входит.
              Пример: \d(?=kg)
              "5kg" -> найдёт "5"
              "5lb" -> не найдёт

(?!...)     - Отрицательная проверка вперёд (Negative Lookahead).
              Проверяет, что справа НЕ находится указанный шаблон.
              Пример: \d(?!kg)
              "5lb" -> найдёт "5"
              "5kg" -> не найдёт

(?<=...)    - Положительная проверка назад (Positive Lookbehind).
              Проверяет, что слева находится указанный шаблон,
              но сам шаблон в результат не входит.
              Пример: (?<=\$)\d+
              "$250" -> найдёт "250"
              "250$" -> не найдёт

(?<!...)    - Отрицательная проверка назад (Negative Lookbehind).
              Проверяет, что слева НЕ находится указанный шаблон.
              Пример: (?<!\$)\d+
              "250"  -> найдёт "250"
              "$250" -> не найдёт

\\          - символ '\'
\.          - символ '.'
\*          - символ '*'
\+          - символ '+'
\?          - символ '?'
\^          - символ '^'
\$          - символ '$'
\[          - символ '['
\]          - символ ']'
\(          - символ '('
\)          - символ ')'
\{          - символ '{'
\}          - символ '}'
\|          - символ '|'

\n          - перевод строки
\r          - возврат каретки
\t          - символ табуляции

------------------------------------------------------------
Примеры
------------------------------------------------------------

^[A-Z]$                 - одна заглавная латинская буква

^[A-Za-z]+$             - только латинские буквы

^\d+$                   - только цифры

^\w+$                   - только буквы, цифры и символ '_'

^[^0-9]+$               - любые символы, кроме цифр

^\d{4}$                 - ровно 4 цифры

^\d{4,6}$               - от 4 до 6 цифр

^[A-Za-z0-9]{8,20}$     - логин длиной от 8 до 20 символов

^\S+@\S+\.\S+$          - простая проверка e-mail

^(https?://).+$         - строка начинается с http:// или https://

^(?=.*[a-z])(?=.*[A-Z])(?=.*\d).{8,}$
            - пароль:
              • минимум 8 символов;
              • хотя бы одна строчная буква;
              • хотя бы одна заглавная буква;
              • хотя бы одна цифра.

^(?=.*[!@#$%^&*()_+\-=\[\]{};':"\\|,.<>/?]).{8,}$
            - строка содержит хотя бы один специальный символ.
*/
#endregion


string passwordPattern = @"^(?=.*[a-z])(?=.*[A-Z])(?=.*\d).{8,}$";
